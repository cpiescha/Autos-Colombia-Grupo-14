CREATE TYPE vehicle_type AS ENUM ('MOTO', 'CARRO', 'CAMIONETA');
CREATE TYPE spot_category AS ENUM ('MOTO', 'AUTOMOVIL');
CREATE TYPE account_role AS ENUM ('ADMINISTRADOR', 'OPERADOR');

CREATE TABLE clients (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL
);

CREATE TABLE operators (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL
);

CREATE TABLE parking_spots (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(20) NOT NULL UNIQUE,
    category   spot_category NOT NULL,
    active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE user_accounts (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id   INTEGER NOT NULL UNIQUE REFERENCES operators (id),
    username      VARCHAR(60) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          account_role NOT NULL,
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_password_is_hash CHECK (
        password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'
    ),
    CONSTRAINT ck_username_normalized CHECK (
        username = lower(username)
        AND username ~ '^[a-z][a-z0-9._]{2,59}$'
    )
);

CREATE TABLE vehicles (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_plate  VARCHAR(10) NOT NULL UNIQUE,
    type           vehicle_type NOT NULL,
    brand          VARCHAR(80) NOT NULL,
    model          VARCHAR(80) NOT NULL,
    color          VARCHAR(40) NOT NULL,
    client_id      INTEGER NOT NULL REFERENCES clients (id)
);

CREATE TABLE memberships (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id INTEGER NOT NULL REFERENCES vehicles (id),
    starts_at  TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_membership_dates CHECK (expires_at > starts_at)
);

CREATE TABLE parking_stays (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id         INTEGER NOT NULL REFERENCES vehicles (id),
    parking_spot_id    INTEGER NOT NULL REFERENCES parking_spots (id),
    entry_operator_id  INTEGER NOT NULL REFERENCES operators (id),
    entered_at         TIMESTAMPTZ NOT NULL,
    exit_operator_id   INTEGER REFERENCES operators (id),
    exited_at          TIMESTAMPTZ,
    CONSTRAINT ck_stay_exit_pair CHECK (
        (exited_at IS NULL AND exit_operator_id IS NULL)
        OR (exited_at IS NOT NULL AND exit_operator_id IS NOT NULL)
    ),
    CONSTRAINT ck_stay_exit_after_entry CHECK (
        exited_at IS NULL OR exited_at >= entered_at
    )
);

CREATE UNIQUE INDEX uq_open_stay_per_vehicle
    ON parking_stays (vehicle_id)
    WHERE exited_at IS NULL;

CREATE UNIQUE INDEX uq_open_stay_per_spot
    ON parking_stays (parking_spot_id)
    WHERE exited_at IS NULL;

CREATE TABLE receipts (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(40) NOT NULL UNIQUE,
    parking_stay_id  INTEGER NOT NULL UNIQUE REFERENCES parking_stays (id),
    used_at          TIMESTAMPTZ
);

CREATE TABLE cell_corrections (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parking_stay_id  INTEGER NOT NULL REFERENCES parking_stays (id),
    previous_spot_id INTEGER NOT NULL REFERENCES parking_spots (id),
    new_spot_id      INTEGER NOT NULL REFERENCES parking_spots (id),
    operator_id      INTEGER NOT NULL REFERENCES operators (id),
    corrected_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_correction_different_spots CHECK (previous_spot_id <> new_spot_id)
);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_user_accounts_updated_at
    BEFORE UPDATE ON user_accounts
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_parking_spots_updated_at
    BEFORE UPDATE ON parking_spots
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE OR REPLACE FUNCTION prevent_delete_spot_with_history()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM parking_stays WHERE parking_spot_id = OLD.id
    ) OR EXISTS (
        SELECT 1
        FROM cell_corrections
        WHERE previous_spot_id = OLD.id OR new_spot_id = OLD.id
    ) THEN
        RAISE EXCEPTION 'SPOT_HAS_HISTORY'
            USING ERRCODE = '23503',
                  HINT = 'Una celda con movimientos se inactiva; no se elimina.';
    END IF;
    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_prevent_delete_spot_with_history
    BEFORE DELETE ON parking_spots
    FOR EACH ROW
    EXECUTE FUNCTION prevent_delete_spot_with_history();

CREATE OR REPLACE FUNCTION prevent_deactivate_occupied_spot()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.active = FALSE AND OLD.active = TRUE AND EXISTS (
        SELECT 1
        FROM parking_stays
        WHERE parking_spot_id = OLD.id
          AND exited_at IS NULL
    ) THEN
        RAISE EXCEPTION 'SPOT_OCCUPIED'
            USING ERRCODE = '23514',
                  HINT = 'No se puede anular una celda con una permanencia abierta.';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_prevent_deactivate_occupied_spot
    BEFORE UPDATE OF active ON parking_spots
    FOR EACH ROW
    EXECUTE FUNCTION prevent_deactivate_occupied_spot();
