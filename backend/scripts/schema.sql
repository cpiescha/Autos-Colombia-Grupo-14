CREATE TYPE vehicle_type AS ENUM ('MOTO', 'CARRO', 'CAMIONETA');
CREATE TYPE spot_category AS ENUM ('MOTO', 'AUTOMOVIL');
CREATE TYPE account_role AS ENUM ('ADMINISTRADOR', 'OPERADOR');

CREATE TABLE clients (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(120) NOT NULL,
    status               VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    inactivated_at       TIMESTAMPTZ,
    inactivated_by       INTEGER,
    inactivation_reason  VARCHAR(255),
    reactivated_at       TIMESTAMPTZ,
    reactivated_by       INTEGER,
    CONSTRAINT ck_client_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE operators (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL
);

CREATE TABLE parking_spots (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(20) NOT NULL UNIQUE,
    category   spot_category NOT NULL,
    active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE user_accounts (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id   INTEGER NOT NULL UNIQUE REFERENCES operators (id),
    username      VARCHAR(60) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          account_role NOT NULL,
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_password_is_hash CHECK (
        password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'
    ),
    CONSTRAINT ck_username_normalized CHECK (
        username = lower(username)
        AND username ~ '^[a-z][a-z0-9._]{2,59}$'
    )
);

CREATE TABLE vehicles (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_plate  VARCHAR(10) NOT NULL UNIQUE,
    type           vehicle_type NOT NULL,
    brand          VARCHAR(80) NOT NULL,
    model          VARCHAR(80) NOT NULL,
    color          VARCHAR(40) NOT NULL,
    client_id      INTEGER NOT NULL REFERENCES clients (id),
    active         BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_vehicle_plate_normalized CHECK (
        license_plate = upper(trim(license_plate)) AND length(license_plate) > 0
    )
);

CREATE TABLE vehicle_audits (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id    INTEGER NOT NULL REFERENCES vehicles (id),
    account_id    INTEGER NOT NULL REFERENCES user_accounts (id),
    action        VARCHAR(10) NOT NULL,
    before_state  JSON,
    after_state   JSON NOT NULL,
    occurred_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_vehicle_audit_action CHECK (action IN ('CREATE', 'UPDATE', 'RETIRE'))
);

CREATE TABLE memberships (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id          INTEGER NOT NULL REFERENCES vehicles (id),
    starts_at           TIMESTAMPTZ NOT NULL,
    expires_at          TIMESTAMPTZ NOT NULL,
    current_cutoff_date TIMESTAMPTZ,
    last_payment_id     INTEGER,
    activated_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_membership_dates CHECK (expires_at > starts_at)
);

CREATE TABLE payments (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id        INTEGER NOT NULL REFERENCES vehicles (id),
    client_id         INTEGER NOT NULL REFERENCES clients (id),
    membership_id     INTEGER NOT NULL REFERENCES memberships (id),
    amount            NUMERIC(12, 2) NOT NULL,
    payment_method    VARCHAR(20) NOT NULL,
    paid_at           TIMESTAMPTZ NOT NULL,
    coverage_start    TIMESTAMPTZ NOT NULL,
    coverage_end      TIMESTAMPTZ NOT NULL,
    previous_cutoff   TIMESTAMPTZ,
    recorded_by       INTEGER NOT NULL REFERENCES user_accounts (id),
    status            VARCHAR(20) NOT NULL DEFAULT 'REGISTERED',
    annulled_at       TIMESTAMPTZ,
    annulled_by       INTEGER REFERENCES user_accounts (id),
    annulment_reason  VARCHAR(255),
    idempotency_key   VARCHAR(80) NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_payments_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_payment_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_payment_method CHECK (
        payment_method IN ('EFECTIVO', 'TRANSFERENCIA', 'QR')
    ),
    CONSTRAINT ck_payment_status CHECK (status IN ('REGISTERED', 'ANNULLED')),
    CONSTRAINT ck_payment_annulment_pair CHECK (
        (status = 'REGISTERED' AND annulled_at IS NULL AND annulled_by IS NULL)
        OR (
            status = 'ANNULLED'
            AND annulled_at IS NOT NULL
            AND annulled_by IS NOT NULL
            AND annulment_reason IS NOT NULL
        )
    ),
    CONSTRAINT ck_payment_coverage CHECK (coverage_end > coverage_start)
);

ALTER TABLE memberships
    ADD CONSTRAINT fk_memberships_last_payment
    FOREIGN KEY (last_payment_id) REFERENCES payments (id);

CREATE TABLE payment_audits (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id     INTEGER NOT NULL REFERENCES payments (id),
    account_id     INTEGER NOT NULL REFERENCES user_accounts (id),
    action         VARCHAR(10) NOT NULL,
    occurred_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    previous_state JSON,
    new_state      JSON NOT NULL,
    CONSTRAINT ck_payment_audit_action CHECK (action IN ('CREATE', 'ANNUL'))
);

CREATE TABLE client_status_audits (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   INTEGER NOT NULL REFERENCES clients (id),
    account_id  INTEGER NOT NULL REFERENCES user_accounts (id),
    action      VARCHAR(20) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reason      VARCHAR(255),
    CONSTRAINT ck_client_status_audit_action CHECK (action IN ('INACTIVATE', 'REACTIVATE'))
);

ALTER TABLE clients
    ADD CONSTRAINT fk_clients_inactivated_by
    FOREIGN KEY (inactivated_by) REFERENCES user_accounts (id);
ALTER TABLE clients
    ADD CONSTRAINT fk_clients_reactivated_by
    FOREIGN KEY (reactivated_by) REFERENCES user_accounts (id);

CREATE TABLE parking_stays (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id         INTEGER NOT NULL REFERENCES vehicles (id),
    parking_spot_id    INTEGER NOT NULL REFERENCES parking_spots (id),
    entry_operator_id  INTEGER NOT NULL REFERENCES operators (id),
    entered_at         TIMESTAMPTZ NOT NULL,
    exit_operator_id   INTEGER REFERENCES operators (id),
    exited_at          TIMESTAMPTZ,
    CONSTRAINT ck_stay_exit_pair CHECK (
        (exited_at IS NULL AND exit_operator_id IS NULL)
        OR (exited_at IS NOT NULL AND exit_operator_id IS NOT NULL)
    ),
    CONSTRAINT ck_stay_exit_after_entry CHECK (
        exited_at IS NULL OR exited_at >= entered_at
    )
);

CREATE UNIQUE INDEX uq_open_stay_per_vehicle
    ON parking_stays (vehicle_id)
    WHERE exited_at IS NULL;

CREATE UNIQUE INDEX uq_open_stay_per_spot
    ON parking_stays (parking_spot_id)
    WHERE exited_at IS NULL;

CREATE TABLE receipts (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(40) NOT NULL UNIQUE,
    parking_stay_id  INTEGER NOT NULL UNIQUE REFERENCES parking_stays (id),
    used_at          TIMESTAMPTZ
);

CREATE TABLE cell_corrections (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parking_stay_id  INTEGER NOT NULL REFERENCES parking_stays (id),
    previous_spot_id INTEGER NOT NULL REFERENCES parking_spots (id),
    new_spot_id      INTEGER NOT NULL REFERENCES parking_spots (id),
    operator_id      INTEGER NOT NULL REFERENCES operators (id),
    corrected_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_correction_different_spots CHECK (previous_spot_id <> new_spot_id)
);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_user_accounts_updated_at
    BEFORE UPDATE ON user_accounts
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_parking_spots_updated_at
    BEFORE UPDATE ON parking_spots
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE OR REPLACE FUNCTION prevent_delete_spot_with_history()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM parking_stays WHERE parking_spot_id = OLD.id
    ) OR EXISTS (
        SELECT 1
        FROM cell_corrections
        WHERE previous_spot_id = OLD.id OR new_spot_id = OLD.id
    ) THEN
        RAISE EXCEPTION 'SPOT_HAS_HISTORY'
            USING ERRCODE = '23503',
                  HINT = 'Una celda con movimientos se inactiva; no se elimina.';
    END IF;
    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_prevent_delete_spot_with_history
    BEFORE DELETE ON parking_spots
    FOR EACH ROW
    EXECUTE FUNCTION prevent_delete_spot_with_history();

CREATE OR REPLACE FUNCTION prevent_deactivate_occupied_spot()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.active = FALSE AND OLD.active = TRUE AND EXISTS (
        SELECT 1
        FROM parking_stays
        WHERE parking_spot_id = OLD.id
          AND exited_at IS NULL
    ) THEN
        RAISE EXCEPTION 'SPOT_OCCUPIED'
            USING ERRCODE = '23514',
                  HINT = 'No se puede anular una celda con una permanencia abierta.';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_prevent_deactivate_occupied_spot
    BEFORE UPDATE OF active ON parking_spots
    FOR EACH ROW
    EXECUTE FUNCTION prevent_deactivate_occupied_spot();
