DO $$
BEGIN
    CREATE TYPE account_role AS ENUM ('ADMINISTRADOR', 'OPERADOR');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS user_accounts (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id   INTEGER NOT NULL UNIQUE REFERENCES operators (id),
    username      VARCHAR(60) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          account_role NOT NULL,
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_password_is_hash CHECK (
        password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'
    ),
    CONSTRAINT ck_username_normalized CHECK (
        username = lower(username)
        AND username ~ '^[a-z][a-z0-9._]{2,59}$'
    )
);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_user_accounts_updated_at ON user_accounts;
CREATE TRIGGER trg_user_accounts_updated_at
    BEFORE UPDATE ON user_accounts
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();
