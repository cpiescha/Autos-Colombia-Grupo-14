-- Apply once to existing T17/T18 databases before deploying T22.
-- Normalization collisions abort the entire transaction; resolve them explicitly.
BEGIN;
ALTER TABLE vehicles ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;
UPDATE vehicles SET license_plate = upper(trim(license_plate));
ALTER TABLE vehicles ADD CONSTRAINT ck_vehicle_plate_normalized CHECK (
    license_plate = upper(trim(license_plate)) AND length(license_plate) > 0
);
CREATE TABLE vehicle_audits (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id INTEGER NOT NULL REFERENCES vehicles (id),
    account_id INTEGER NOT NULL REFERENCES user_accounts (id),
    action VARCHAR(10) NOT NULL,
    before_state JSON,
    after_state JSON NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_vehicle_audit_action CHECK (action IN ('CREATE', 'UPDATE', 'RETIRE'))
);
COMMIT;
